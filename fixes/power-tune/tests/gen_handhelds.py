#!/usr/bin/env python3
"""Writes fixes/power-tune/handhelds.txt: EVERY handheld row of app/data/devices.json
(the power-tune verbs that touch firmware power limits or battery modes act only on
these). Same format and code as tools/fixes/gen_handhelds.py, without its filter.

Also writes fixes/power-tune/ppt-limits.txt: the most watts set_ppt may write per
handheld (devices.json tdp.sppt_max / fppt_max, else boost_max, else plugged_max),
so the root helper never goes past the documented safe boost limits even if the
app asked it to. "<id>\tsppt=<W>\tfppt=<W>".

    python3 -I fixes/power-tune/tests/gen_handhelds.py          rewrite both files
    python3 -I fixes/power-tune/tests/gen_handhelds.py --check  exit 1 when one is stale
"""
import json
import importlib.util
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
OUT = os.path.join(REPO, "fixes", "power-tune", "handhelds.txt")
spec = importlib.util.spec_from_file_location("gen", os.path.join(REPO, "tools", "fixes", "gen_handhelds.py"))
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)
gen.uses_fixes = lambda row: True
text = gen.render().replace(
    "# Handhelds the fan and charge-limit fixes may write to (DMI ids, shell globs, any case).",
    "# Every handheld GameCove knows: power-tune sets firmware power limits and battery modes only on these.").replace(
    "tools/fixes/gen_handhelds.py", "fixes/power-tune/tests/gen_handhelds.py")
LIMITS = os.path.join(REPO, "fixes", "power-tune", "ppt-limits.txt")


def limits():
    lines = ["# Generated by fixes/power-tune/tests/gen_handhelds.py from app/data/devices.json; do not edit.",
             "# Most watts power-tune writes to ppt_pl2_sppt / ppt_pl3_fppt per handheld (hhd / maker safe limits)."]
    for row in json.load(open(os.path.join(REPO, "app", "data", "devices.json"), encoding="utf-8"))["devices"]:
        t = row.get("tdp")
        if not isinstance(t, dict):
            continue
        top = t.get("boost_max", t.get("plugged_max"))
        lines.append("%s\tsppt=%d\tfppt=%d" % (row["id"], t.get("sppt_max", top), t.get("fppt_max", top)))
    return "\n".join(lines) + "\n"


if "--check" in sys.argv[1:]:
    for path, want in ((OUT, text), (LIMITS, limits())):
        have = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if have != want:
            print("%s is stale: run python3 -I fixes/power-tune/tests/gen_handhelds.py" % os.path.relpath(path, REPO), file=sys.stderr)
            sys.exit(1)
    sys.exit(0)
open(OUT, "w", encoding="utf-8").write(text)
open(LIMITS, "w", encoding="utf-8").write(limits())
