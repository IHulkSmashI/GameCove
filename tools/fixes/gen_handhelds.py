#!/usr/bin/env python3
"""Writes fixes/lib/handhelds.txt from app/data/devices.json.

The fan and charge-limit fixes write to drivers that laptops share (MSI's
msi_wmi_platform, ASUS's asus-wmi), so they only act when the DMI ids match a
handheld row that uses them. This keeps that list in step with devices.json:

    python3 tools/fixes/gen_handhelds.py          rewrite the file
    python3 tools/fixes/gen_handhelds.py --check  exit 1 when it is stale

Format (one alternative per line, tab-separated key=pattern|pattern fields,
shell globs, compared case-insensitively; every key must match):
    <device id>\tsys_vendor=AYANEO\tproduct_name=AYANEO 3
"""
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(REPO, "app", "data", "devices.json")
OUT = os.path.join(REPO, "fixes", "lib", "handhelds.txt")
KEYS = ("sys_vendor", "product_name", "board_name", "board_vendor", "product_family")


def uses_fixes(row):
    return (row.get("fan_via") == "fix"
            or row.get("charge_limit_via") in ("fix", "sysfs")
            or "fan" in row.get("fixes", []) or "charge-limit" in row.get("fixes", []))


def render():
    rows = json.load(open(SRC, encoding="utf-8"))["devices"]
    lines = [
        "# Generated by tools/fixes/gen_handhelds.py from app/data/devices.json; do not edit.",
        "# Handhelds the fan and charge-limit fixes may write to (DMI ids, shell globs, any case).",
    ]
    for row in rows:
        if not uses_fixes(row):
            continue
        alts = row["match"] if isinstance(row["match"], list) else [row["match"]]
        for alt in alts:
            fields = []
            for key in KEYS:
                if key in alt:
                    pats = [str(p) for p in alt[key]]
                    for p in pats:
                        if "|" in p or "\t" in p or "\n" in p:
                            raise SystemExit("%s: pattern %r can't go in handhelds.txt" % (row["id"], p))
                    fields.append("%s=%s" % (key, "|".join(pats)))
            if set(alt) - set(KEYS):
                raise SystemExit("%s: unknown match key" % row["id"])
            if fields:
                lines.append("\t".join([row["id"]] + fields))
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print("fixes/lib/handhelds.txt is stale: run python3 tools/fixes/gen_handhelds.py", file=sys.stderr)
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
