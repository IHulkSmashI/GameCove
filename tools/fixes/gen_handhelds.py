#!/usr/bin/env python3
"""Writes fixes/lib/handhelds.txt, fixes/lib/devices.txt and fixes/lib/fix-devices.txt from
app/data/devices.json and app/data/fixes.json, and each devices.json row's "fixes" field.

The fan and charge-limit fixes write to drivers that laptops share (MSI's
msi_wmi_platform, ASUS's asus-wmi), so they only act when the DMI ids match a
handheld row that uses them. This keeps that list in step with devices.json:

    python3 tools/fixes/gen_handhelds.py          rewrite both files
    python3 tools/fixes/gen_handhelds.py --check  exit 1 when one is stale

fix-devices.txt names, per folder fix, every handheld it may act on (auto + optional, resolved
from the fix's trait selectors by tools/traits/traits.py; "*" = any handheld). gcfix.sh reads it
for DEVICES="@", and builds each udev rule's DMI match from those handhelds' devices.txt lines, so
a rule written on one handheld of a shared drive only ever acts on handhelds with the trait.
devices.json "fixes" (what the installer applies) is the fix catalogue's "auto" resolved per row.

devices.txt lists every row (specific rows before family rows, so the first
match is the most specific one); fixes/lib/gcfix.sh looks the handheld's id up
there and each fix only acts on the ids it names.

Format (one alternative per line, tab-separated key=pattern|pattern fields,
shell globs, compared case-insensitively; every key must match):
    <device id>\tsys_vendor=AYANEO\tproduct_name=AYANEO 3
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "traits"))
import traits  # noqa: E402  (tools/traits/traits.py)

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(REPO, "app", "data", "devices.json")
OUT = os.path.join(REPO, "fixes", "lib", "handhelds.txt")
OUT_ALL = os.path.join(REPO, "fixes", "lib", "devices.txt")
OUT_FIX = os.path.join(REPO, "fixes", "lib", "fix-devices.txt")
FIXES = os.path.join(REPO, "app", "data", "fixes.json")
TIER = {"specific": 0, "family": 1, "generic": 2}
KEYS = ("sys_vendor", "product_name", "board_name", "board_vendor", "product_family")


def uses_fixes(row):
    return (row.get("fan_via") == "fix"
            or row.get("charge_limit_via") in ("fix", "sysfs")
            or "fan" in row.get("fixes", []) or "charge-limit" in row.get("fixes", []))


def row_lines(row):
    out = []
    alts = row["match"] if isinstance(row["match"], list) else [row["match"]]
    for alt in alts:
        fields = []
        for key in KEYS:
            if key in alt:
                pats = [str(p) for p in alt[key]]
                for p in pats:
                    if "|" in p or "\t" in p or "\n" in p:
                        raise SystemExit("%s: pattern %r can't go in handhelds.txt" % (row["id"], p))
                fields.append("%s=%s" % (key, "|".join(pats)))
        if set(alt) - set(KEYS):
            raise SystemExit("%s: unknown match key" % row["id"])
        if fields:
            out.append("\t".join([row["id"]] + fields))
    return out


def render():
    rows = json.load(open(SRC, encoding="utf-8"))["devices"]
    lines = [
        "# Generated by tools/fixes/gen_handhelds.py from app/data/devices.json; do not edit.",
        "# Handhelds the fan and charge-limit fixes may write to (DMI ids, shell globs, any case).",
    ]
    for row in rows:
        if uses_fixes(row):
            lines.extend(row_lines(row))
    return "\n".join(lines) + "\n"


def render_all():
    rows = json.load(open(SRC, encoding="utf-8"))["devices"]
    lines = [
        "# Generated by tools/fixes/gen_handhelds.py from app/data/devices.json; do not edit.",
        "# Every handheld row, specific before family (first match wins). Used by fixes/lib/gcfix.sh.",
    ]
    order = sorted(range(len(rows)), key=lambda i: (TIER.get(rows[i].get("tier"), 3), i))
    for i in order:
        lines.extend(row_lines(rows[i]))
    return "\n".join(lines) + "\n"


def render_fix_devices():
    rows = json.load(open(SRC, encoding="utf-8"))["devices"]
    cat = json.load(open(FIXES, encoding="utf-8"))["fixes"]
    lines = [
        "# Generated by tools/fixes/gen_handhelds.py from app/data/fixes.json + devices.json traits; do not edit.",
        "# <fix>\t<devices.json ids it may act on (auto + optional), or *>. Used by fixes/lib/gcfix.sh (DEVICES=\"@\").",
    ]
    for e in cat:
        if e.get("kind") not in ("root", "file"):
            continue
        if traits.is_everywhere(e.get("auto")) or traits.is_everywhere(e.get("optional")):
            ids = ["*"]
        else:
            sets = traits.fix_sets(e, rows)
            want = set(sets["auto"]) | set(sets["optional"])
            ids = [r["id"] for r in rows if r["id"] in want]
        lines.append("%s\t%s" % (e["id"], " ".join(ids)))
    return "\n".join(lines) + "\n"


def render_devices_json():
    """devices.json with each row's "fixes" line set to the catalogue's auto resolution."""
    text = open(SRC, encoding="utf-8").read()
    rows = json.loads(text)["devices"]
    cat = json.load(open(FIXES, encoding="utf-8"))["fixes"]
    want = {r["id"]: traits.auto_fixes(r, cat) for r in rows}
    out = []
    cur = None
    for line in text.split("\n"):
        m = re.match(r'^      "id": "([^"]+)",$', line)
        if m:
            cur = m.group(1)
        if cur and re.match(r'^      "fixes": \[.*\],$', line):
            line = '      "fixes": %s,' % json.dumps(want[cur])
        out.append(line)
    new = "\n".join(out)
    got = {r["id"]: r["fixes"] for r in json.loads(new)["devices"]}
    if got != want:
        raise SystemExit("devices.json: a row's \"fixes\" isn't on one line; can't regenerate it")
    return new


def main():
    files = ((OUT, render()), (OUT_ALL, render_all()), (OUT_FIX, render_fix_devices()), (SRC, render_devices_json()))
    if "--check" in sys.argv[1:]:
        rc = 0
        for path, text in files:
            have = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if have != text:
                print("%s is stale: run python3 tools/fixes/gen_handhelds.py" % os.path.relpath(path, REPO), file=sys.stderr)
                rc = 1
        return rc
    for path, text in files:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
