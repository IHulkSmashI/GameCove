#!/usr/bin/env python3
"""Checks every fixes/<id>/fix.json and builds what is generated from them.

    python3 tools/fixes/build.py            rewrite app/data/fixes.json, the README table and
                                            the catalogue in docs/FIXES.md
    python3 tools/fixes/build.py --check    exit 1 when a definition is wrong or a generated
                                            file is stale (CI, packaging/tests/run.sh)
    python3 tools/fixes/build.py --dist D   also write D/fixes.json, the file the nightly
                                            workflow signs and publishes (tools/fixes/audit.py
                                            adds what it observed)

One file per fix is the source: fixes/<id>/fix.json, checked against tools/fixes/fix.schema.json
(a JSON Schema; validated here with a small standard-library validator so the signing job needs
no third-party package, and cross-checked with the jsonschema package in the tests when it is
installed) and against the rules a schema can't express (rules()). docs/FIXES.md explains every
field. Standard library only.
"""
