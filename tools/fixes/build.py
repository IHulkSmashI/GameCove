# ------------------------------------------------------------------ a small JSON Schema validator

def _type_ok(value, name):
    if name == "null":
        return value is None
    if name == "boolean":
        return isinstance(value, bool)
    if name == "integer":
        return isinstance(value, int) and not isinstance(value, bool)
    if name == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    if name == "string":
        return isinstance(value, str)
    if name == "array":
        return isinstance(value, list)
    if name == "object":
        return isinstance(value, dict)
    raise ValueError("schema type %r isn't supported" % name)


SUPPORTED = {"$schema", "$id", "$defs", "$ref", "title", "description", "type", "const", "enum", "required",
             "properties", "additionalProperties", "items", "minItems", "minLength", "maxLength", "pattern",
             "minimum", "anyOf"}


def validate(value, schema, root=None, where="$"):
    """Problems (strings) of `value` against the subset of JSON Schema fix.schema.json uses."""
    root = schema if root is None else root
    unknown = set(schema) - SUPPORTED
    if unknown:
        raise ValueError("schema keyword(s) not supported here: %s" % ", ".join(sorted(unknown)))
    if "$ref" in schema:
        ref = schema["$ref"]
        if not ref.startswith("#/$defs/"):
            raise ValueError("only #/$defs/ references are supported: %s" % ref)
        return validate(value, root["$defs"][ref[8:]], root, where)
    out = []
    if "const" in schema and value != schema["const"]:
        out.append("%s: must be %r" % (where, schema["const"]))
    if "enum" in schema and value not in schema["enum"]:
        out.append("%s: %r isn't one of %s" % (where, value, ", ".join(repr(e) for e in schema["enum"])))
    if "type" in schema and not _type_ok(value, schema["type"]):
        return out + ["%s: must be %s" % (where, schema["type"])]
    if "anyOf" in schema:
        tries = [validate(value, s, root, where) for s in schema["anyOf"]]
        if all(tries):
            best = min(tries, key=len)
            out.append("%s: matches none of the allowed shapes (closest: %s)" % (where, "; ".join(best[:2])))
    if isinstance(value, str):
        if len(value) < schema.get("minLength", 0):
            out.append("%s: shorter than %d characters" % (where, schema["minLength"]))
        if "maxLength" in schema and len(value) > schema["maxLength"]:
            out.append("%s: longer than %d characters" % (where, schema["maxLength"]))
        if "pattern" in schema and not re.search(schema["pattern"], value):
            out.append("%s: %r doesn't match %s" % (where, value, schema["pattern"]))
    if _type_ok(value, "number") and "minimum" in schema and value < schema["minimum"]:
        out.append("%s: below %s" % (where, schema["minimum"]))
    if isinstance(value, list):
        if len(value) < schema.get("minItems", 0):
            out.append("%s: needs at least %d item(s)" % (where, schema["minItems"]))
        if "items" in schema:
            for i, v in enumerate(value):
                out.extend(validate(v, schema["items"], root, "%s[%d]" % (where, i)))
    if isinstance(value, dict):
        for k in schema.get("required", []):
            if k not in value:
                out.append("%s: missing %r" % (where, k))
        props = schema.get("properties", {})
        extra = schema.get("additionalProperties", True)
        for k, v in value.items():
            if k in props:
                out.extend(validate(v, props[k], root, "%s.%s" % (where, k)))
            elif extra is False:
                out.append("%s: unknown key %r" % (where, k))
            elif isinstance(extra, dict):
                out.extend(validate(v, extra, root, "%s.%s" % (where, k)))
    return out


def load_schema():
    with open(SCHEMA, encoding="utf-8") as f:
        return json.load(f)


# ------------------------------------------------------------------ the definitions

def fix_ids(fixes_dir=FIXES_DIR):
    """Every folder under fixes/ that is a fix: it holds a fix.sh or a fix.json."""
    out = []
    for name in sorted(os.listdir(fixes_dir)):
        d = os.path.join(fixes_dir, name)
        if os.path.isdir(d) and (os.path.isfile(os.path.join(d, "fix.sh")) or os.path.isfile(os.path.join(d, "fix.json"))):
            out.append(name)
    return out


def load_all(fixes_dir=FIXES_DIR):
    """({id: definition}, [problems]) for every fix folder."""
    schema = load_schema()
    defs, problems = {}, []
    for name in fix_ids(fixes_dir):
        path = os.path.join(fixes_dir, name, "fix.json")
        if not os.path.isfile(path):
            problems.append("fixes/%s: no fix.json (every fix needs its definition)" % name)
            continue
        try:
            with open(path, encoding="utf-8") as f:
                d = json.load(f)
        except (OSError, ValueError) as e:
            problems.append("fixes/%s/fix.json: %s" % (name, e))
            continue
        errs = validate(d, schema)
        problems.extend("fixes/%s/fix.json: %s" % (name, e) for e in errs)
        if not errs:
            defs[name] = d
    return defs, problems


def conditions(cond):
    """Every leaf condition inside a condition (all / any / not unpacked)."""
    if not isinstance(cond, dict):
        return []
    for k in ("all", "any"):
        if k in cond:
            return [leaf for c in cond[k] for leaf in conditions(c)]
    if "not" in cond:
        return conditions(cond["not"])
    return [cond]


def _script(name, fixes_dir):
    p = os.path.join(fixes_dir, name, "fix.sh")
    return open(p, encoding="utf-8").read() if os.path.isfile(p) else ""


def script_revision(text):
    m = re.search(r"^REVISION=([0-9]+)\b", text, re.M)
    return int(m.group(1)) if m else 1


def rules(defs, rows, fixes_dir=FIXES_DIR):
    """What the schema can't say. rows: devices.json rows."""
    out = []
    ids = {r["id"] for r in rows}
    for name, d in sorted(defs.items()):
        w = "fixes/%s/fix.json" % name
        if d["id"] != name:
            out.append("%s: id %r isn't the folder name" % (w, d["id"]))
        script = _script(name, fixes_dir)
        kind = d["kind"]
        if kind in ("root", "file", "power"):
            if not script:
                out.append("%s: kind %s needs fixes/%s/fix.sh" % (w, kind, name))
            if not (os.path.isfile(os.path.join(fixes_dir, name, "test.sh"))):
                out.append("%s: needs fixes/%s/test.sh (tests against a fake root)" % (w, name))
            # undo and probe: the script answers remove and status
            for verb in ("remove", "status"):
                if script and not re.search(r"(^|[\s|(])%s\)" % verb, script) and "gc_main" not in script:
                    out.append("%s: fix.sh has no %r command (%s)" % (w, verb, "undo" if verb == "remove" else "probe"))
            if d["lifecycle"]["probe"]["command"] != "status":
                out.append("%s: a fix with a script names `status` as its probe" % w)
        elif script:
            out.append("%s: kind %s has no script, but fixes/%s/fix.sh exists" % (w, kind, name))
        if kind in ("root", "file"):
            if script and script_revision(script) != d["revision"]:
                out.append("%s: revision %d, but fix.sh says REVISION=%d" % (w, d["revision"], script_revision(script)))
            if script and "gc_main" not in script and not re.search(r"^update\)", script, re.M):
                out.append("%s: fix.sh has no `update` command" % w)
            if d["password"] != "admin":
                out.append("%s: a fix that installs files needs the admin password" % w)
            if not d["changes"]:
                out.append("%s: list what it changes" % w)
            has_auto = not (isinstance(d["auto"], list) and not d["auto"])
            if (d["level"] == "recommended") != has_auto:
                out.append("%s: Recommended means preselected: level recommended needs an \"auto\" selector, "
                           "optional must not have one" % w)
            if d["default"] != ("on" if d["level"] == "recommended" else "suggested-off"):
                out.append("%s: default must be %s for level %s" % (w, "on" if d["level"] == "recommended" else "suggested-off", d["level"]))
            if d["lifecycle"]["obsolete_when"] is None:
                out.append("%s: needs obsolete_when (at least {\"probe\": \"os_fixed\"}), so the handheld can tell "
                           "when the system has caught up" % w)
            if d["lifecycle"]["probe"]["native"] != "os_fixed=yes":
                out.append("%s: its probe must report os_fixed=yes when the system does it natively" % w)
            if script and "os_fixed" not in script:
                out.append("%s: fix.sh status never prints os_fixed=" % w)
        if kind == "advice":
            if d["default"] != "advice-only" or d["changes"] or d["level"] != "optional" or not d["must_fix"]:
                out.append("%s: advice is text for a must-fix problem with no software fix: default advice-only, "
                           "no changes, level optional, must_fix true" % w)
            if not (isinstance(d["auto"], list) and not d["auto"]):
                out.append("%s: advice has no \"auto\" selector (nothing is applied); use \"optional\"" % w)
        elif d["default"] == "advice-only":
            out.append("%s: default advice-only is for kind advice" % w)
        if d["level"] == "recommended" and not d["must_fix"]:
            out.append("%s: Recommended is only for must-fix problems" % w)
        if d["level"] == "recommended" and d["risk"] == "high":
            out.append("%s: a high-risk fix can't be Recommended" % w)
        if d["must_fix"] != bool(d["breaks"]):
            out.append("%s: must_fix and breaks go together (breaks names the core function it restores)" % w)
        for key in ("auto", "optional"):
            for p in traits.selector_problems(d[key], "%s %s" % (w, key)):
                out.append(p)
        if d["page"] == "fixes" and kind != "app":
            if not traits.is_everywhere(d["auto"]) and not traits.is_everywhere(d["optional"]) \
                    and not (traits.resolve(d["auto"], rows) or traits.resolve(d["optional"], rows)):
                out.append("%s: its selectors pick no handheld" % w)
        for dev in d.get("exclude", {}):
            if dev not in ids:
                out.append("%s: excluded device %r isn't in devices.json" % (w, dev))
        for t in d["tested"]:
            if t["device"] not in ids:
                out.append("%s: tested device %r isn't in devices.json" % (w, t["device"]))
        seen = set()
        for x in d["watch"]:
            if x["id"] in seen:
                out.append("%s: watch id %r is used twice" % (w, x["id"]))
            seen.add(x["id"])
            need = {"github-file": ("repo", "path"), "github-commits": ("repo", "path"), "github-release": ("repo",),
                    "github-issue": ("repo", "number"), "gitlab-tags": ("project",), "kernel-releases": (),
                    "firmware-index": ("device", "item"), "lore": ("query",), "url": ("url",)}[x["kind"]]
            for k in need:
                if k not in x:
                    out.append("%s: watch %r (%s) needs %r" % (w, x["id"], x["kind"], k))
            if "records" in x and x["kind"] != "github-file":
                out.append("%s: watch %r: only github-file watches can record a result by themselves" % (w, x["id"]))
            if x["kind"] == "firmware-index" and x.get("device") not in ids:
                out.append("%s: watch %r names a device that isn't in devices.json" % (w, x["id"]))
        for key in ("needed_when", "obsolete_when"):
            for leaf in conditions(d["lifecycle"][key]):
                if "probe" in leaf and d["lifecycle"]["probe"]["command"] != "status":
                    out.append("%s: %s uses a probe, but the fix has none" % (w, key))
        if kind in ("root", "file") and d["page"] == "fixes" and not d["watch"]:
            out.append("%s: needs at least one watch entry for the nightly audit" % w)
    return out


def device_rows():
    with open(os.path.join(REPO, "app", "data", "devices.json"), encoding="utf-8") as f:
        return json.load(f)["devices"]


def ordered(defs):
    known = [i for i in ORDER if i in defs]
    return known + sorted(i for i in defs if i not in ORDER)


def resolved_devices(d, rows):
    """Who the fix is for, resolved: "*" or [{"id", "level", "match"}] (match: the row's DMI ids)."""
    if d["kind"] == "app" or traits.is_everywhere(d["auto"]):
        return "*"
    sets = traits.fix_sets(d, rows)
    out = []
    for r in rows:
        if r["id"] in sets["auto"] or r["id"] in sets["optional"]:
            out.append({"id": r["id"], "level": "recommended" if r["id"] in sets["auto"] else "optional", "match": r["match"]})
    if traits.is_everywhere(d["optional"]):
        return {"listed": out, "others": "optional"}
    return out


def build_doc(defs, rows):
    fixes = []
    for i in ordered(defs):
        e = dict(defs[i])
        e.pop("schema", None)
        e["devices"] = resolved_devices(e, rows)
        fixes.append(e)
    return {"_about": ABOUT, "schema": DATA_SCHEMA, "version": 1, "fixes": fixes}


def render_json(doc):
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


# ------------------------------------------------------------------ README table and docs catalogue

def _names(d, rows, which):
    if which == "auto" and traits.is_everywhere(d["auto"]):
        return "Every handheld"
    if which == "optional" and traits.is_everywhere(d["optional"]):
        return "Any handheld with the part"
    sets = traits.fix_sets(d, rows)
    names = [r["name"] for r in rows if r["id"] in sets[which] and r.get("tier") == "specific"]
    return ", ".join(names)


def _short(names, limit=6):
    parts = names.split(", ") if names else []
    if len(parts) <= limit:
        return names
    return ", ".join(parts[:limit]) + " and %d more" % (len(parts) - limit)


def _tested(d, rows):
    by = {r["id"]: r["name"] for r in rows}
    return "; ".join("%s (%s, %s)" % (by.get(t["device"], t["device"]), t["os"], t["date"]) for t in d["tested"])


def _level_cell(d, rows):
    rec = _names(d, rows, "auto")
    opt = _names(d, rows, "optional")
    cells = []
    if rec:
        cells.append("**Recommended**: " + _short(rec))
    if opt:
        cells.append("**Optional**: " + _short(opt))
    return "<br>".join(cells)


def readme_table(defs, rows):
    lines = ["| Fix | Restores | For | Tested on hardware | Your system today |",
             "| --- | --- | --- | --- | --- |"]
    for i in ordered(defs):
        d = defs[i]
        if d["page"] != "fixes" or not d["must_fix"] or d["kind"] == "advice":
            continue
        today = "Bazzite: %s SteamOS: %s" % (d["bazzite"], d["steamos"])
        lines.append("| **%s**<br>%s | %s | %s | %s | %s |" % (
            d["title"], d["line"], BREAKS[d["breaks"]], _level_cell(d, rows), _tested(d, rows) or "Not yet", today))
    return "\n".join(lines) + "\n"


def _cond_text(c):
    if c is None:
        return "always"
    return "`%s`" % json.dumps(c, ensure_ascii=False)


def _link(s):
    return "<%s>" % s if s.startswith("https://") else s


def docs_catalogue(defs, rows):
    out = []
    for i in ordered(defs):
        d = defs[i]
        level = "Advice" if d["kind"] == "advice" else d["level"].capitalize()
        out.append("### %s" % i)
        out.append("")
        out.append("**%s** · %s%s · risk: %s · revision %d · last audited %s" % (
            d["title"], level, " · restores: %s" % BREAKS[d["breaks"]].lower() if d["breaks"] else "", d["risk"], d["revision"], d["audited"]))
        out.append("")
        out.append(d["line"] + (" " + d["symptom"] if d["symptom"] else ""))
        out.append("")
        rec, opt = _names(d, rows, "auto"), _names(d, rows, "optional")
        if d["kind"] == "advice":
            out.append("- Shown on: %s" % (opt or "no handheld"))
        elif d["page"] == "fixes":
            if rec:
                out.append("- Recommended on: %s" % rec)
            if opt:
                out.append("- Optional on: %s" % opt)
        else:
            out.append("- A setting on the %s page, not a workaround: it has no lifecycle." % d["page"].capitalize())
        for c in d["changes"]:
            out.append("- Changes (%s): `%s`. %s" % (c["type"], c["target"], c["detail"]))
        out.append("- Undo: %s" % d["undo"])
        out.append("- Risk: %s" % d["risk_note"])
        out.append("- Tested on hardware: %s" % (_tested(d, rows) or "not yet"))
        if d["bazzite"] or d["steamos"]:
            out.append("- Bazzite: %s SteamOS: %s" % (d["bazzite"], d["steamos"]))
        if d["page"] == "fixes" and d["kind"] != "app":
            lc = d["lifecycle"]
            out.append("- Needed when: %s" % _cond_text(lc["needed_when"]))
            out.append("- Not needed any more when: %s" % _cond_text(lc["obsolete_when"]).replace("`null`", "never (nothing upstream to wait for)"))
            out.append("- Probe: %s" % lc["probe"]["what"])
            out.append("- With the system's own fix also active: %s" % ("harmless (the same setting twice)" if lc["both_active"] == "harmless" else "they would conflict, so GameCove's copy must go"))
        for w in d["watch"]:
            target = w.get("repo", w.get("project", w.get("url", w.get("device", w.get("query", "")))))
            extra = " `%s`" % w["path"] if w.get("path") else (" #%d" % w["number"] if "number" in w else "")
            out.append("- Watches (%s): %s%s. %s%s" % (w["kind"], target, extra, w["note"],
                       " Recorded by the audit itself." if "records" in w else ""))
        out.append("- Sources: %s" % "; ".join(_link(s) for s in d["sources"]))
        if d["withdrawn"]:
            out.append("- **Withdrawn %s**: %s" % (d["withdrawn"]["date"], d["withdrawn"]["reason"]))
        out.append("")
    return "\n".join(out)


def splice(text, name, body):
    """Replaces what is between <!-- fixes:<name>:start --> and <!-- fixes:<name>:end -->."""
    a = "<!-- fixes:%s:start -->" % name
    b = "<!-- fixes:%s:end -->" % name
    if a not in text or b not in text:
        raise SystemExit("markers %s / %s not found" % (a, b))
    head, rest = text.split(a, 1)
    tail = rest.split(b, 1)[1]
    return head + a + "\n" + body + b + tail


README_HEAD = "| Fix | Restores | For | Tested on hardware | Your system today |"


def splice_table(text, body):
    """Replaces the README table that starts with README_HEAD, down to its last "|" line. (The README
    carries no hidden comments, packaging/tests/release.sh: the table's own header is the marker.)"""
    lines = text.split("\n")
    if lines.count(README_HEAD) != 1:
        raise SystemExit("README: exactly one table must start with %r" % README_HEAD)
    a = lines.index(README_HEAD)
    b = a
    while b < len(lines) and lines[b].startswith("|"):
        b += 1
    return "\n".join(lines[:a] + body.rstrip("\n").split("\n") + lines[b:])


def generated(defs, rows):
    """{path: text} for every generated file."""
    out = {OUT: render_json(build_doc(defs, rows))}
    if os.path.isfile(README):
        with open(README, encoding="utf-8") as f:
            out[README] = splice_table(f.read(), readme_table(defs, rows))
    if os.path.isfile(DOC):
        with open(DOC, encoding="utf-8") as f:
            out[DOC] = splice(f.read(), "catalogue", docs_catalogue(defs, rows))
    return out


def main(argv):
    defs, problems = load_all()
    rows = device_rows()
    if not problems:
        problems = rules(defs, rows)
    if problems:
        for p in problems:
            print(p, file=sys.stderr)
        return 1
    files = generated(defs, rows)
    if "--check" in argv:
        rc = 0
        for path, text in files.items():
            have = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
            if have != text:
                print("%s is stale: run python3 tools/fixes/build.py" % os.path.relpath(path, REPO), file=sys.stderr)
                rc = 1
        return rc
    for path, text in files.items():
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    if "--dist" in argv:
        dist = argv[argv.index("--dist") + 1]
        os.makedirs(dist, exist_ok=True)
        with open(os.path.join(dist, "fixes.json"), "w", encoding="utf-8") as f:
            f.write(render_json(build_doc(defs, rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
